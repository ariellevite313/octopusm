-- Tickers réservés : les 100 premiers DRC-20 natifs (doggy.market, classement par volume total, 15/11/2026).
-- Personne ne peut lancer un token avec ces tickers sur OM, sauf les wallets de l'équipe du projet, ajoutés par l'admin
-- après une demande vérifiée (table ticker_requests). x_handle : compte X connu du projet (pour vérifier la demande).

CREATE TABLE IF NOT EXISTS public.reserved_tickers (
  ticker          text PRIMARY KEY,               -- en majuscules, sans « $ » (format des tickers OM)
  original        text NOT NULL,                  -- ticker d'origine (ex. $wen)
  source          text NOT NULL DEFAULT 'drc20',
  rank            integer,
  x_handle        text,
  allowed_wallets text[] NOT NULL DEFAULT '{}',   -- wallets de l'équipe autorisés à lancer ce ticker
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.ticker_requests (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticker      text NOT NULL,
  wallet      text NOT NULL,
  x_handle    text NOT NULL,
  contact     text,
  message     text,
  status      text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz
);
CREATE INDEX IF NOT EXISTS ticker_requests_status ON public.ticker_requests (status, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ticker_requests_one_pending ON public.ticker_requests (ticker, wallet) WHERE status = 'pending';

-- Lecture et écriture par le serveur seulement (clé service)
ALTER TABLE public.reserved_tickers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ticker_requests  ENABLE ROW LEVEL SECURITY;

