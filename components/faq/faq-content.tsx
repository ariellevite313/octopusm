export default function FaqContent() {
  const { tr } = useT();

  // Renders a list item; "{faq}" marks where the italic cross-reference goes.
  function renderLi(raw: string, i: number) {
    const text = tr(raw);
    if (text.includes("{faq}")) {
      const [before, after] = text.split("{faq}");
      return (
        <li key={i}>
          <Rich>{before}</Rich>
          <em>{tr("Which wallets should I use?")}</em>
          <Rich>{after}</Rich>
        </li>
      );
    }
    return <li key={i}><Rich>{text}</Rich></li>;
  }

  return (
    <main className="mx-auto max-w-2xl px-4 py-8 pb-24 space-y-10">
      {/* Header */}
      <div className="space-y-2">
        <h1 className="text-2xl font-bold text-foreground">{tr("Official FAQ")}</h1>
        <p className="text-sm text-muted-foreground leading-relaxed">
          {tr("We are building an on-chain platform on Solana that brings together prediction markets and a Launchpad. Our goal is simple: let you create, trade, and earn on the real activity of your community.")}
        </p>
        <div className="flex flex-wrap gap-3 pt-1">
          <a
            href="https://omdot.fun"
            className="inline-flex items-center gap-1 text-xs text-violet-600 dark:text-violet-400 hover:underline"
          >
            omdot.fun <ExternalLink className="size-3" />
          </a>
          <a
            href="https://x.com/OMdotFun"
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex items-center gap-1 text-xs text-violet-600 dark:text-violet-400 hover:underline"
          >
            @OMdotFun <ExternalLink className="size-3" />
          </a>
        </div>
      </div>

      {/* Sections */}
      {SECTIONS.map((section) => (
        <section key={section.title} className="space-y-3">
          <h2 className="text-base font-semibold text-foreground border-b border-border pb-2">
            {tr(section.title)}
          </h2>
          <div className="space-y-4">
            {section.items.map((item) => (
              <div key={item.q} className="space-y-1">
                <h3 className="text-sm font-semibold text-foreground">{tr(item.q)}</h3>
                <div className="text-sm text-muted-foreground leading-relaxed">
                  {item.a.map((b, bi) =>
                    typeof b === "string" ? (
                      <Rich key={bi}>{tr(b)}</Rich>
                    ) : "ol" in b ? (
                      <ol key={bi} className={b.cls}>{b.ol.map(renderLi)}</ol>
                    ) : (
                      <ul key={bi} className={b.cls}>{b.ul.map(renderLi)}</ul>
                    ),
                  )}
                </div>
              </div>
            ))}
          </div>
        </section>
      ))}

      {/* Disclaimer */}
      <p className="text-xs text-muted-foreground border-t border-border pt-6">
        <Rich linkClass="text-violet-600 dark:text-violet-400 hover:underline">
          {tr("Trading prediction markets and launching a token involve a risk of loss. Always check the current terms on [omdot.fun](/) before acting.")}
        </Rich>
      </p>
    </main>
  );
}
